/** The curated policy starter packs and the RepoProfile keying that selects them
 *  (issue #400).
 *
 *  WHY PRESETS. Policy authoring started from a blank textbox, so the realistic
 *  outcome for a new project was no policy at all — governed autonomy with the
 *  rails left unbuilt. These packs are the floor a repo of this shape almost
 *  always wants, written in the exact syntax the matchers implement (every entry
 *  is asserted clean by `PolicyStarterPacks.utils.test.tsx`, so a pack can never
 *  ship a rule the editor would flag as dead).
 *
 *  WHAT THEY ARE NOT. A pack only ever ADDS deny/ask rules, never `allowTools`:
 *  a wrong guess must fail toward MORE friction, never toward a hole in the
 *  rails. And applying one is a draft edit, not a write — the author still reads
 *  the rules and saves them. */
import type {
  PolicyPackKey,
  PolicyPackLists,
  PolicyProfileHints,
  PolicyStarterPack,
} from './PolicyStarterPacks.types';

/** True when the profile lists `language` (case-insensitively). */
function hasLanguage(profile: PolicyProfileHints, language: string): boolean {
  return profile.languages.some((value) => value.toLowerCase() === language);
}

/** True when the profile lists `framework` (case-insensitively). */
function hasFramework(profile: PolicyProfileHints, framework: string): boolean {
  return profile.frameworks.some((value) => value.toLowerCase() === framework);
}

