/**
 * The packs to offer for a repo shape. A `null` profile (never scanned) offers
 * only the universal packs rather than guessing — an irrelevant pack that adds
 * rules for a stack the repo does not have is noise the author has to audit.
 */
export function packsForProfile(
  profile: PolicyProfileHints | null,
): readonly PolicyStarterPack[] {
  return STARTER_PACKS.filter(
    (pack) =>
      pack.appliesTo === null || (profile !== null && pack.appliesTo.matches(profile)),
  );
}

/** True when every entry of the pack is already in the draft — the pack has
 *  nothing left to contribute, so its button reads as done rather than inviting a
 *  no-op click. */
export function packApplied(pack: PolicyStarterPack, current: PolicyPackLists): boolean {
  return Object.entries(pack.entries).every(([key, entries]) => {
    const existing = new Set(current[key as PolicyPackKey].map((value) => value.trim()));
    return (entries ?? []).every((entry) => existing.has(entry));
  });
}

/** How many rules a pack contributes, for the card's summary line. */
export function packRuleCount(pack: PolicyStarterPack): number {
  return Object.values(pack.entries).reduce((total, entries) => total + entries.length, 0);
}
